import { useCallback, useEffect, useState } from "react";
import { api } from "./api.js";
import { Badge, Section } from "./ui.jsx";

function Faq({ user, isAdmin }) {
	const [items, setItems] = useState([]);
	const [error, setError] = useState("");
	const load = useCallback(() => { api("/faq").then((d) => setItems(d.faq)).catch((e) => setError(e.message)); }, []);
	useEffect(load, [load]);
	async function add(event) {
		event.preventDefault();
		const f = event.target;
		try {
			await api("/faq", { user, method: "POST", json: { question: f.question.value, answer: f.answer.value, language: f.language.value } });
			f.reset();
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	async function remove(id) {
		try {
			await api(`/faq/${id}`, { user, method: "DELETE" });
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	return (
		<Section eyebrow="Help" title="Frequently asked questions" description="Plain answers maintained by the platform admin; not generated by the model.">
			{items.length === 0 && <p className="ad-muted">No entries yet.</p>}
			<div className="ad-faq">
				{items.map((q) => (
					<details key={q.id}>
						<summary><Badge>{q.language}</Badge> {q.question}</summary>
						<p>{q.answer}</p>
						{isAdmin && <button type="button" className="ad-link-button" onClick={() => remove(q.id)}>Delete</button>}
					</details>
				))}
			</div>
			{isAdmin && (
				<form className="ad-form ad-controls" onSubmit={add}>
					<p className="eyebrow">Add an entry (admin)</p>
					<label>Question<input name="question" type="text" required minLength={3} maxLength={500} /></label>
					<label>Answer<input name="answer" type="text" required maxLength={4000} /></label>
					<label>Language<select name="language" defaultValue="en"><option value="en">English</option><option value="fr">Français</option></select></label>
					<button type="submit" className="review-primary-action">Add</button>
				</form>
			)}
			{error && <div className="review-error" role="alert">{error}</div>}
		</Section>
	);
}

function Support({ user, isAdmin, projectId }) {
	const [items, setItems] = useState([]);
	const [error, setError] = useState("");
	const [sent, setSent] = useState(false);
	const load = useCallback(() => { api("/support-requests", { user }).then((d) => setItems(d.support_requests)).catch((e) => setError(e.message)); }, [user]);
	useEffect(load, [load]);
	async function create(event) {
		event.preventDefault();
		const f = event.target;
		try {
			await api("/support-requests", { user, method: "POST", json: { subject: f.subject.value, body: f.body.value, category: f.category.value, project_id: f.attach?.checked ? projectId : null } });
			f.reset();
			setSent(true);
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	async function setStatus(id, status) {
		try {
			await api(`/support-requests/${id}`, { user, method: "PATCH", json: { status } });
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	return (
		<Section eyebrow="Support" title={isAdmin ? "Support requests (admin)" : "Contact support"}>
			{!isAdmin && (
				<form className="ad-form ad-controls" onSubmit={create}>
					<label>Subject<input name="subject" type="text" required minLength={3} maxLength={200} /></label>
					<label>Describe the problem<textarea name="body" required minLength={3} rows={4} maxLength={5000} /></label>
					<label>Category
						<select name="category" defaultValue="question"><option value="question">Question</option><option value="bug">Bug</option><option value="account">Account</option><option value="other">Other</option></select>
					</label>
					{projectId && <label><span><input type="checkbox" name="attach" defaultChecked /> About the current project ({projectId})</span></label>}
					<button type="submit" className="review-primary-action">Send request</button>
					{sent && <p className="ad-muted" role="status">Request recorded.</p>}
				</form>
			)}
			<p className="eyebrow">{isAdmin ? "All requests" : "My requests"}</p>
			{items.length === 0 && <p className="ad-muted">None.</p>}
			<ul className="ad-list">
				{items.map((r) => (
					<li key={r.id}>
						<strong>{r.subject}</strong>
						<small>{r.category} · {r.status.replace("_", " ")} · {r.created_at.slice(0, 16).replace("T", " ")}{isAdmin ? ` · ${r.user_id}` : ""}</small>
						{isAdmin && (
							<span className="ad-row">
								{["open", "in_progress", "closed"].filter((s) => s !== r.status).map((s) => (
									<button key={s} type="button" className="ad-link-button" onClick={() => setStatus(r.id, s)}>Mark {s.replace("_", " ")}</button>
								))}
							</span>
						)}
					</li>
				))}
			</ul>
			{error && <div className="review-error" role="alert">{error}</div>}
		</Section>
	);
}

export default function Help({ user, role, projectId }) {
	return (
		<div className="ad-split">
			<div className="ad-split__side"><Faq user={user} isAdmin={role === "admin"} /></div>
			<div className="ad-split__main">
				{user ? <Support user={user} isAdmin={role === "admin"} projectId={projectId} /> : (
					<Section eyebrow="Support" title="Contact support"><p className="ad-muted">Choose a demo identity to send a support request.</p></Section>
				)}
			</div>
		</div>
	);
}
