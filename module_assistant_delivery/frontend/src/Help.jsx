import { useCallback, useEffect, useState } from "react";
import { api } from "./api.js";
import { Expand, Field, Pending, Section, Tag } from "./ui.jsx";

const STATUS = { open: ["Open", "warn"], in_progress: ["In progress", "accent"], closed: ["Closed", "neutral"] };
const when = (iso) => iso.slice(0, 16).replace("T", " ");

function FaqItem({ q, user, isAdmin, onChanged }) {
	const [editing, setEditing] = useState(false);
	const [error, setError] = useState("");
	async function save(event) {
		event.preventDefault();
		const f = event.target;
		try {
			await api(`/faq/${q.id}`, { user, method: "PUT", json: { question: f.question.value, answer: f.answer.value, language: f.language.value } });
			setEditing(false);
			onChanged();
		} catch (e) {
			setError(e.message);
		}
	}
	async function remove() {
		try {
			await api(`/faq/${q.id}`, { user, method: "DELETE" });
			onChanged();
		} catch (e) {
			setError(e.message);
		}
	}
	return (
		<details>
			<summary><Tag>{q.language.toUpperCase()}</Tag>{q.question}</summary>
			{editing ? (
				<form className="ad-form ad-inline-form" onSubmit={save}>
					<Field label="Question"><input name="question" type="text" defaultValue={q.question} required minLength={3} maxLength={500} /></Field>
					<Field label="Answer"><textarea name="answer" defaultValue={q.answer} required rows={3} maxLength={4000} /></Field>
					<div className="ad-form__row">
						<Field label="Language"><select name="language" defaultValue={q.language}><option value="en">English</option><option value="fr">Français</option></select></Field>
						<div className="ad-row">
							<button type="submit" className="ad-btn ad-btn--primary ad-btn--sm">Save</button>
							<button type="button" className="ad-btn ad-btn--sm" onClick={() => setEditing(false)}>Cancel</button>
						</div>
					</div>
				</form>
			) : (
				<>
					<p>{q.answer}</p>
					{isAdmin && (
						<span className="ad-row">
							<button type="button" className="ad-link" onClick={() => setEditing(true)}>Edit</button>
							<button type="button" className="ad-link" onClick={remove}>Delete</button>
						</span>
					)}
				</>
			)}
			{error && <div className="ad-alert" role="alert">{error}</div>}
		</details>
	);
}

function Faq({ user, isAdmin }) {
	const [items, setItems] = useState([]);
	const [error, setError] = useState("");
	const load = useCallback(() => { api("/faq").then((d) => setItems(d.faq)).catch((e) => setError(e.message)); }, []);
	useEffect(load, [load]);
	async function add(event) {
		event.preventDefault();
		const f = event.target;
		try {
			await api("/faq", { user, method: "POST", json: { question: f.question.value, answer: f.answer.value, language: f.language.value } });
			f.reset();
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	return (
		<Section title="Frequently asked questions" description="Plain answers kept by the platform admin, not generated by the model.">
			{items.length === 0 && <p className="ad-muted">No entries yet.</p>}
			<div className="ad-faq">
				{items.map((q) => <FaqItem key={q.id} q={q} user={user} isAdmin={isAdmin} onChanged={load} />)}
			</div>
			{isAdmin && (
				<form className="ad-form" onSubmit={add}>
					<Field label="Question (new entry)"><input name="question" type="text" required minLength={3} maxLength={500} /></Field>
					<Field label="Answer"><textarea name="answer" required rows={2} maxLength={4000} /></Field>
					<div className="ad-form__row">
						<Field label="Language"><select name="language" defaultValue="en"><option value="en">English</option><option value="fr">Français</option></select></Field>
						<button type="submit" className="ad-btn ad-btn--primary">Add entry</button>
					</div>
				</form>
			)}
			{error && <div className="ad-alert" role="alert">{error}</div>}
		</Section>
	);
}

// One support request: the row opens into the original message, the reply thread and the actions.
function SupportRequest({ r, user, isAdmin, onChanged }) {
	const [open, setOpen] = useState(false);
	const [detail, setDetail] = useState(null);
	const [error, setError] = useState("");
	const [draft, setDraft] = useState("");
	const [busy, setBusy] = useState(false);
	const load = useCallback(() => {
		api(`/support-requests/${r.id}`, { user }).then(setDetail).catch((e) => setError(e.message));
	}, [r.id, user]);
	useEffect(() => { if (open) load(); }, [open, load, r.updated_at]);

	async function reply(event) {
		event.preventDefault();
		if (!draft.trim()) return;
		setBusy(true);
		try {
			await api(`/support-requests/${r.id}/messages`, { user, method: "POST", json: { body: draft } });
			setDraft("");
			onChanged();
			load();
		} catch (e) {
			setError(e.message);
		} finally {
			setBusy(false);
		}
	}
	async function setStatus(status) {
		try {
			await api(`/support-requests/${r.id}`, { user, method: "PATCH", json: { status } });
			onChanged();
		} catch (e) {
			setError(e.message);
		}
	}

	const [label, tone] = STATUS[r.status];
	const actions = isAdmin
		? [r.status !== "in_progress" && ["in_progress", "Mark in progress"], r.status !== "closed" ? ["closed", "Close"] : ["open", "Reopen"]].filter(Boolean)
		: [r.status === "closed" ? ["open", "Reopen"] : ["closed", "Close my request"]];
	return (
		<li className="ad-ticket" data-open={open}>
			<button type="button" className="ad-ticket__head" aria-expanded={open} onClick={() => setOpen((o) => !o)}>
				<span className="ad-ticket__title"><strong>{r.subject}</strong><Tag tone={tone}>{label}</Tag></span>
				<small>
					{r.category}, opened {when(r.created_at)}{isAdmin ? `, by ${r.user_id}` : ""}
					{r.replies ? `, ${r.replies} ${r.replies === 1 ? "reply" : "replies"}` : ", no reply yet"}
				</small>
			</button>
			<Expand open={open}>
				<div className="ad-ticket__body">
					{!detail ? <Pending>Loading the request…</Pending> : (
						<>
							<ol className="ad-thread-list">
								<li className="is-requester">
									<span className="ad-thread-list__who">{isAdmin ? r.user_id : "You"}, {when(detail.support_request.created_at)}</span>
									<p>{detail.support_request.body}</p>
								</li>
								{detail.messages.map((m) => (
									<li key={m.id} className={m.author_role === "admin" ? "is-admin" : "is-requester"}>
										<span className="ad-thread-list__who">
											{m.author_role === "admin" ? "Support" : isAdmin ? m.author_id : "You"}, {when(m.created_at)}
										</span>
										<p>{m.body}</p>
									</li>
								))}
							</ol>
							<form className="ad-form" onSubmit={reply}>
								<Field label={isAdmin ? "Reply to the requester" : "Add a message"}>
									<textarea rows={3} maxLength={5000} value={draft} onChange={(e) => setDraft(e.target.value)} />
								</Field>
								<div className="ad-row">
									<button type="submit" className="ad-btn ad-btn--primary ad-btn--sm" disabled={!draft.trim() || busy}>{busy ? "Sending…" : "Send"}</button>
									{actions.map(([status, text]) => (
										<button key={status} type="button" className="ad-btn ad-btn--sm" onClick={() => setStatus(status)}>{text}</button>
									))}
								</div>
							</form>
						</>
					)}
					{error && <div className="ad-alert" role="alert">{error}</div>}
				</div>
			</Expand>
		</li>
	);
}

function Support({ user, isAdmin, projectId }) {
	const [items, setItems] = useState([]);
	const [error, setError] = useState("");
	const [sent, setSent] = useState(false);
	const load = useCallback(() => { api("/support-requests", { user }).then((d) => setItems(d.support_requests)).catch((e) => setError(e.message)); }, [user]);
	useEffect(load, [load]);
	async function create(event) {
		event.preventDefault();
		const f = event.target;
		try {
			await api("/support-requests", { user, method: "POST", json: { subject: f.subject.value, body: f.body.value, category: f.category.value, project_id: f.attach?.checked ? projectId : null } });
			f.reset();
			setSent(true);
			load();
		} catch (e) {
			setError(e.message);
		}
	}
	return (
		<>
			{!isAdmin && (
				<Section title="Contact support">
					<form className="ad-form" onSubmit={create}>
						<Field label="Subject"><input name="subject" type="text" required minLength={3} maxLength={200} /></Field>
						<Field label="Describe the problem"><textarea name="body" required minLength={3} rows={4} maxLength={5000} /></Field>
						<Field label="Category">
							<select name="category" defaultValue="question"><option value="question">Question</option><option value="bug">Bug</option><option value="account">Account</option><option value="other">Other</option></select>
						</Field>
						{projectId && <label className="ad-check"><input type="checkbox" name="attach" defaultChecked /> About the current project ({projectId})</label>}
						<div className="ad-row">
							<button type="submit" className="ad-btn ad-btn--primary">Send request</button>
							{sent && <span className="ad-muted" role="status">Request recorded. Replies appear under My requests.</span>}
						</div>
					</form>
				</Section>
			)}
			<Section title={isAdmin ? "All support requests" : "My requests"}
				description={isAdmin ? "Open a request to read it, reply, and move it along." : "Open a request to read replies from support."}>
				{items.length === 0 && <p className="ad-muted">None.</p>}
				<ul className="ad-tickets">
					{items.map((r) => <SupportRequest key={r.id} r={r} user={user} isAdmin={isAdmin} onChanged={load} />)}
				</ul>
				{error && <div className="ad-alert" role="alert">{error}</div>}
			</Section>
		</>
	);
}

export default function Help({ user, role, projectId }) {
	return (
		<div className="ad-split">
			<div className="ad-split__side"><Faq user={user} isAdmin={role === "admin"} /></div>
			<div className="ad-split__main">
				{user ? <Support user={user} isAdmin={role === "admin"} projectId={projectId} /> : (
					<Section title="Contact support"><p className="ad-muted">Choose a demo identity to send a support request.</p></Section>
				)}
			</div>
		</div>
	);
}
